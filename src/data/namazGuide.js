// ── Генератор шагов намаза ────────────────────────────────────────────────────
function sec(label, color = "#F5EAD4") {
  return { type: "section", label, color };
}

function step(position, note, items) {
  return { type: "step", position, note: note || null, items: items || [] };
}

function ayah(arabic, translit, translation, repeat, audioUrl = null) {
  return { arabic, translit, translation, repeat: repeat || null, audioUrl };
}

function buildRakaat(n, total, prayerName) {
  const items = [];
  const isFirst = n === 1;
  const isLast = n === total;
  const isMiddleTashahhud = n === 2 && total > 2;

  // ── Сана (только в 1-м ракаате) ──
  if (isFirst) {
    items.push(sec(`ДУА САНА (1-Й РАКААТ)`, "#F5EAD4"));
    items.push(step("standing_folded", "Правую руку кладёшь на левую у пупка или на груди", [
      ayah("سُبْحَانَكَ اللَّهُمَّ وَبِحَمْدِكَ وَتَبَارَكَ اسْمُكَ وَتَعَالَى جَدُّكَ وَلَا إِلَهَ غَيْرُكَ",
        "Субhааналлааhумма ва биhамдика ва табаракасмука ва та'аляя джаддука ва ляя иляяhа гайрук.",
        "Пречист Ты, о Аллах, хвала Тебе, благословенно Твоё имя, велико Твоё могущество, нет бога кроме Тебя.")
    ]));
  }

  // ── Аль-Фатиха ──
  items.push(sec(`СУРА АЛЬ-ФАТИХА (${n}-Й РАКААТ)`, "#F5EAD4"));
  items.push(step("standing_folded", isFirst ? "Читай про себя (тихо)" : null,
    FATIHA_AYAHS.map((a) => ayah(a.arabic, a.translit, a.translation, null, a.audioUrl))
  ));

  // ── Короткая сура (1-й и 2-й ракааты) ──
  if (n <= 2) {
    items.push(sec(`СУРА АЛЬ-ИХЛАС (${n}-Й РАКААТ)`, "#dcfce7"));
    items.push(step("standing_folded", "После Фатихи читай любую суру. Например Аль-Ихляс:",
      IKHLAS_AYAHS.map((a) => ayah(a.arabic, a.translit, a.translation, null, a.audioUrl))
    ));
  }

  // ── Руку ──
  items.push(sec(`ПОЯСНОЙ ПОКЛОН — РУКУЪ (${n}-Й РАКААТ)`, "#F5EAD4"));
  items.push(step("ruku", "Наклонись — спина горизонтальна, руки на коленях", [
    ayah("سُبْحَانَ رَبِّيَ الْعَظِيمِ", "Субhаана Раббийаль-'Азыым!", "Пречист мой Господь Великий!", "Г—3")
  ]));

  // ── Итидаль ──
  items.push(sec(`ВЫПРЯМЛЕНИЕ — ИТИДАЛЬ (${n}-Й РАКААТ)`, "#F5EAD4"));
  items.push(step("standing", "Поднимись и полностью выпрямись", [
    ayah("سَمِعَ اللَّهُ لِمَنْ حَمِدَهُ", "Сами'аллааhу лиман hамидаh.", "Услышал Аллах того, кто восхвалил Его."),
    ayah("رَبَّنَا لَكَ الْحَمْدُ", "Раббана ляка аль-хамд!", "О Господь наш, Тебе хвала!")
  ]));

  // ── Суджуд 1 ──
  items.push(sec(`ЗЕМНОЙ ПОКЛОН — СУДЖУД 1 (${n}-Й РАКААТ)`, "#F5EAD4"));
  items.push(step("sujud", "7 частей тела касаются пола: лоб вместе с носом, две ладони, два колена и пальцы двух стоп.", [
    ayah("سُبْحَانَ رَبِّيَ الْأَعْلَى", "Субhаана Раббийаль-А'ляя!", "Пречист мой Господь Всевышний!", "Г—3")
  ]));

  // ── Джалса ──
  items.push(sec(`СИДЕНИЕ МЕЖДУ ПОКЛОНАМИ (${n}-Й РАКААТ)`, "#F5EAD4"));
  items.push(step("sitting", "Сядь, левая ступня под тебя, правая — вертикально", [
    ayah("رَبِّ اغْفِرْ لِي", "Раббигфир лий!", "Господь мой, прости меня!")
  ]));

  // ── Суджуд 2 ──
  items.push(sec(`ЗЕМНОЙ ПОКЛОН — СУДЖУД 2 (${n}-Й РАКААТ)`, "#F5EAD4"));
  items.push(step("sujud", "Повтори земной поклон", [
    ayah("سُبْحَانَ رَبِّيَ الْأَعْلَى", "Субhаана Раббийаль-А'ляя!", "Пречист мой Господь Всевышний!", "Г—3")
  ]));

  // ── Средний Ташаhhуд (после 2-го ракаата в 3/4-ракаатных намазах) ──
  if (isMiddleTashahhud) {
    items.push(sec("АТ-ТАШАHHУД (СРЕДНИЙ)", "#F5EAD4"));
    items.push(step("sitting", "Сядь. Указательный палец поднят при «Ашhаду»",
      TASHAHHUD_PARTS.map((a) => ayah(a.arabic, a.translit, a.translation))
    ));
    items.push(sec("ПОДЪЁМ НА СЛЕДУЮЩИЙ РАКААТ", "#F5EAD4"));
    items.push(step("standing", "Встань для следующего ракаата. Читай только Фатиху — суру не читаешь", []));
  }

  // ── Заключительный Ташаhhуд ──
  if (isLast) {
    items.push(sec("АТ-ТАШАHHУД (ЗАКЛЮЧИТЕЛЬНЫЙ)", "#F5EAD4"));
    items.push(step("sitting", "Сядь. Указательный палец поднят при «Ашhаду»",
      TASHAHHUD_PARTS.map((a) => ayah(a.arabic, a.translit, a.translation))
    ));

    items.push(sec("САЛЯВАТ", "#F5EAD4"));
    items.push(step("sitting", "Читается после Ташаhhуда в последнем ракаате",
      SALAWAT_PARTS.map((a) => ayah(a.arabic, a.translit, a.translation))
    ));

    items.push(sec("ЗАВЕРШЕНИЕ — САЛЯМ", "#dcfce7"));
    items.push(step("sitting", "Поверни голову вправо и произнеси, затем влево:", [
      ayah("السَّلَامُ عَلَيْكُمْ وَرَحْمَةُ اللَّهِ", "Ас-саляму 'аляйкум ва рахматуллааh!", "Мир вам и милость Аллаха!")
    ]));
  }

  return items;
}

export function buildPrayerGuide(prayer) {
  const items = [];

  // ── Намерение ──
  items.push(sec("НАМЕРЕНИЕ ПЕРЕД НАМАЗОМ", "#e0f2fe"));
  items.push(step("standing", `Совершив ритуальное омовение, необходимо встать ровно, обратившись на Каабу, и сделать намерение про себя:\n«${prayer.name} намаз-фард, ${prayer.rakaats} ракаата»`, []));

  // ── Такбир ──
  items.push(sec("ВСТУПИТЕЛЬНЫЙ ТАКБИР", "#F5EAD4"));
  items.push(step("takbir", "Подними руки до ушей. Большие пальцы касаются мочек ушей.", [
    ayah("اللَّهُ أَكْبَرُ", "Аллааhу Акбар!", "Аллах — Величайший!")
  ]));

  // ── Ракааты ──
  for (let r = 1; r <= prayer.rakaats; r++) {
    items.push(...buildRakaat(r, prayer.rakaats, prayer.name));
  }

  return items;
}

